# ============================================================
# BUILD TELEMETRY
# ============================================================

points = [
    make_point(seconds, weight)
    for seconds, weight in weights
]


# ============================================================
# RUN
# ============================================================

print(
    f"Generated telemetry points: {len(points)}"
)

session = sessionize(points)


if session is None:

    print("❌ No session detected.")

else:

    print_session(session)